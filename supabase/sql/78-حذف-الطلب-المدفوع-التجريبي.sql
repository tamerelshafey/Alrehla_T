-- ============================================================
-- 78 — حذف الطلب التجريبي المدفوع `ALR-000002-KF`
-- ============================================================
--
-- ⚠️ **حذف نهائي.** مفيش تراجع بعد `COMMIT`.
--
-- ── ليه ملف مستقل ───────────────────────────────────────────
--
--   السطر ده كان معلّقًا في ملف 77 عن قصد: حالته `paid` بـ650 ج.م،
--   ومسح سجل مكتوب عليه «مدفوع» بيتاخد بقرار صريح مش بالجملة. تامر
--   أكّد إنه تجريبي — فبقى الحذف بقرار، وده الملف اللي بينفّذه.
--
-- ── تصحيح: علامة الـ✗ في تأكيد ملف 77 كانت غلط مني ─────────
--
--   استعلام التأكيد رجّع «رسائل المحادثة · 3 · لسه فيه صفوف ✗».
--   **ده مش فشل في التنظيف — ده خطأ في استعلام التأكيد نفسه.**
--
--   حطّيت `متوقع_صفر = true` على عدّاد الرسائل كله، وأنا نفسي سايب
--   `ALR-000002-KF` عايش عن قصد ورسايله معاه. يعني كتبت شرط تأكيد
--   بيناقض قرار في نفس الملف.
--
--   والدليل إن الأرقام سليمة: ملف 76 عدّ **3 رسائل** في القاعدة كلها
--   قبل التنظيف، وبعد التنظيف لسه **3**. يعني جملة حذف الرسائل في
--   ملف 77 مسحت صفر صفوف — الطلبات الخمسة اللي اتمسحت مكانش عليها
--   ولا رسالة أصلًا، والتلاتة كلهم على `ALR-000002-KF`.
--
--   الملف ده بيمسحهم معاه، والعدّاد هيوصل صفر دلوقتي بجد.
--
-- ── الترتيب ─────────────────────────────────────────────────
--
--   الأبناء قبل الأب عشان المفاتيح الأجنبية:
--     1) الرسائل      2) التقييمات (احتياط)      3) الطلب
--
--   جملة التقييمات احتياطية: ملف 76 بيّن العدد، ولو صفر الجملة بتمسح
--   صفر صفوف بلا خطأ. سايبها عشان لو كان فيه تقييم مربوط، الطلب
--   مكانش هيتمسح وكنا هنقع في خطأ مفتاح أجنبي بدل حذف نظيف.
-- ============================================================

BEGIN;

-- ------------------------------------------------------------
-- 1) رسائل محادثة الطلب (المتوقع: 3)
-- ------------------------------------------------------------
DELETE FROM public.service_order_messages
WHERE order_id IN (
  SELECT id FROM public.service_orders
  WHERE payment_reference = 'ALR-000002-KF'
);

-- ------------------------------------------------------------
-- 2) تقييمات مربوطة بالطلب — احتياط
-- ------------------------------------------------------------
DELETE FROM public.reviews
WHERE service_order_id IN (
  SELECT id FROM public.service_orders
  WHERE payment_reference = 'ALR-000002-KF'
);

-- ------------------------------------------------------------
-- 3) الطلب نفسه
-- ------------------------------------------------------------
DELETE FROM public.service_orders
WHERE payment_reference = 'ALR-000002-KF';

COMMIT;

-- ============================================================
-- تأكيد — استعلام واحد
--
-- المتوقع دلوقتي: `service_orders` فاضي، الرسائل صفر، والحجز
-- `ALR-000012-R3` وجلساته الاثنتي عشرة زي ما هما.
--
-- ⚠️ الشروط هنا مكتوبة صح المرة دي: العدّادات اللي **المفروض**
--    تبقى صفر متعلّم عليها `true`، واللي المفروض تفضل زي ما هي
--    متعلّم عليها `false`.
-- ============================================================
SELECT البند, العدد::text AS العدد, الحالة FROM (
  SELECT البند, العدد,
         CASE WHEN متوقع_صفر AND العدد = 0 THEN 'اتنضّف ✓'
              WHEN متوقع_صفر               THEN 'لسه فيه صفوف ✗'
              WHEN NOT متوقع_صفر AND العدد = 0 THEN '⚠️ اتمسح بالغلط'
              ELSE 'ما اتلمسش ✓' END AS الحالة,
         ترتيب
  FROM (
    SELECT 'طلبات الخدمات'::text AS البند,
           (SELECT count(*) FROM public.service_orders) AS العدد,
           true AS متوقع_صفر, 1 AS ترتيب
    UNION ALL
    SELECT 'رسائل المحادثة',
           (SELECT count(*) FROM public.service_order_messages), true, 2
    UNION ALL
    SELECT 'تقييمات مربوطة بطلب خدمة',
           (SELECT count(*) FROM public.reviews WHERE service_order_id IS NOT NULL), true, 3
    UNION ALL
    SELECT 'الحجوزات (course_subscriptions)',
           (SELECT count(*) FROM public.course_subscriptions), false, 4
    UNION ALL
    SELECT 'الجلسات',
           (SELECT count(*) FROM public.sessions), false, 5
    UNION ALL
    SELECT 'حسابات المستخدمين',
           (SELECT count(*) FROM public.user_profiles), false, 6
    UNION ALL
    SELECT 'الخدمات (standalone_services)',
           (SELECT count(*) FROM public.standalone_services), false, 7
  ) x
) t ORDER BY ترتيب;


-- ============================================================
-- 64 — إزاحة الجلسات القائمة للتوقيت المحلي
-- ============================================================
--
-- المشكلة:
--
--   الكود كان بيبني ميعاد الجلسة بـ`setHours()`، وهي بتستخدم التوقيت
--   المحلي **للخادم** — وخادم Vercel بيشتغل UTC.
--
--   فالمدرب اللي اختار «18:00» في جدوله، جلساته اتسجّلت 18:00 UTC،
--   واللي بيشوفها في مصر بيقرا **21:00**. تلات ساعات فرق في كل جلسة
--   اتولّدت قبل إصلاح 18 سبتمبر.
--
--   الكود اتصلّح: التوليد بقى بساعة الحيطة في القاهرة، والتوقيت الصيفي
--   بيتحسب لوحده. **لكن الجلسات اللي اتولّدت قبل كده لسه بالقيمة
--   الغلط** — الإصلاح بيأثر على الجديد بس.
--
-- اللي الملف ده بيعمله:
--
--   بيطرح إزاحة القاهرة من كل جلسة **قادمة** لسه ما تمّتش، عشان ساعة
--   الحيطة بتاعتها ترجع زي ما المدرب قصدها.
--
--   مثال: جلسة مسجّلة 18:00 UTC (بتبان 21:00 للمستخدم) بتبقى 15:00 UTC
--   — يعني 18:00 بتوقيت القاهرة، وهو المقصود من الأول.
--
--   `AT TIME ZONE` بتاخد التوقيت الصيفي في حسابها لكل جلسة على حدة، فمفيش
--   رقم «3 ساعات» مكتوب في الملف.
--
-- ⚠️ حدود مقصودة:
--   • الجلسات **اللي فاتت** مابتتلمسش — هي سجل لحاجة حصلت، ومالهاش
--     لازمة تتعدّل.
--   • الجلسات **المكتملة أو الملغية** مابتتلمسش لنفس السبب.
--   • الجلسات اللي الإدارة عدّلت ميعادها بإيدها من شاشة الجلسات **هتتزاح
--     كمان** — لأن مفيش في القاعدة حاجة تفرّق بين ميعاد متولّد وميعاد
--     متعدّل باليد. شغّل ملف 65 (تشخيص) الأول وشوف القايمة، ولو فيها
--     جلسة اتظبطت يدويًا بلّغني قبل ما تشغّل الملف ده.
--
-- التراجع في آخر الملف: بيجمع الإزاحة تاني.
-- ============================================================

BEGIN;

UPDATE public.sessions
SET
  scheduled_at = scheduled_at
    - (
        -- إزاحة القاهرة عن UTC في تاريخ الجلسة نفسها (بتتغيّر مع
        -- التوقيت الصيفي).
        (scheduled_at AT TIME ZONE 'Africa/Cairo') - (scheduled_at AT TIME ZONE 'UTC')
      ),
  updated_at = now()
WHERE scheduled_at > now()
  AND status NOT IN ('completed', 'cancelled');

COMMIT;

-- ============================================================
-- تأكيد — استعلام واحد
--
-- «الساعة المعروضة» هي اللي المستخدم في مصر بيشوفها. المفروض تطابق
-- الميعاد اللي المدرب حاطه في جدوله.
-- ============================================================
SELECT
  s.id                                                          AS الجلسة,
  COALESCE(i.display_name, '—')                                 AS المدرب,
  s.session_number                                              AS رقم_الجلسة,
  s.status                                                      AS الحالة,
  to_char(s.scheduled_at AT TIME ZONE 'Africa/Cairo',
          'YYYY-MM-DD HH24:MI')                                 AS الساعة_المعروضة,
  to_char(s.scheduled_at AT TIME ZONE 'UTC',
          'YYYY-MM-DD HH24:MI')                                 AS المخزَّن_UTC,
  CASE WHEN s.scheduled_at > now() THEN 'قادمة — اتزاحت'
       ELSE 'فاتت — ما اتلمستش' END                             AS ملاحظة
FROM public.sessions s
LEFT JOIN public.instructors i ON i.id = s.instructor_id
ORDER BY s.scheduled_at;


-- ============================================================
-- 67 — تنظيف الحجوزات التجريبية
-- ============================================================
--
-- ⚠️ **الملف ده بيمسح نهائيًا.** مفيش سلة مهملات في Postgres ومفيش
--    تراجع بعد `COMMIT`. اقرا الأعداد تحت قبل ما تشغّله.
--
-- السياق: الموقع لسه في التطوير وما اشتغلش، وتامر طلب تنظيف الحجوزات
-- السابقة والبدء من جديد.
--
-- تشخيص ملف 66 على القاعدة الحقيقية طلّع:
--
--   • اشتراكان (حجزان)، الاتنين «الكلمات الذهبية» وحالتهم active:
--       - ALR-000010-55 ← صفر جلسة (البند المعلّق: اتحوّل لـ«نشط»
--         قبل ما توليد الجلسات يتضاف للمشروع)
--       - ALR-000011-VK ← 12 جلسة
--   • 12 جلسة
--   • **صفر** تقرير جلسة · **صفر** رسالة · **صفر** مرفق
--   • **صفر** تقييم مربوط بحجز
--
-- يعني مفيش أي حاجة معلّقة على الحجوزات غير الجلسات نفسها، والتنظيف
-- بياخد جدولين بس.
--
-- ── اللي **مش** بيتلمس ──────────────────────────────────────
--
--   الباقات (6) · المدربون (2) · حسابات المستخدمين (13) ·
--   طلبات الخدمات الإبداعية (6) · عروض مقدّمي الخدمة (12) ·
--   نصوص معرض الطلاب (0)
--
--   الحسابات بتفضل زي ما هي عن قصد: العميل يقدر يحجز من جديد بنفس
--   حسابه، ومفيش داعي يسجّل تاني.
--
-- ── أثر جانبي مقصود ─────────────────────────────────────────
--
--   مواعيد المدرب بترجع متاحة **تلقائيًا**. الإتاحة بقت تتحسب من
--   الجلسات القادمة (مش من علامة مخزَّنة)، فمسح الجلسات بيفضّي مواعيدها
--   من غير أي خطوة زيادة.
--
--   والرقم المرجعي للحجز الجديد بيتولّد في القاعدة، فمفيش تعارض مع
--   ALR-000010 و ALR-000011 المحذوفين.
--
-- ── الترتيب ─────────────────────────────────────────────────
--
--   الأبناء قبل الآباء عشان المفاتيح الأجنبية. الجداول الفاضية
--   موجودة في الملف عن قصد: لو حد أضاف صف بينها وبين ما شغّلته، الملف
--   يفضل شغّال بدل ما يقع على قيد مفتاح أجنبي.
-- ============================================================

BEGIN;

-- 1) تقارير الجلسات (0 حاليًا)
DELETE FROM public.session_reports
WHERE session_id IN (SELECT id FROM public.sessions);

-- 2) الجلسات (12)
DELETE FROM public.sessions;

-- 3) الاشتراكات — الحجوزات نفسها (2)
DELETE FROM public.course_subscriptions;

COMMIT;

-- ملاحظة: `session_messages` و`session_attachments` مش في الملف لأن
-- عمودهم `booking_id` بيشاور على جدول `bookings` القديم، مش على
-- `course_subscriptions`. والاتنين فاضيين (0 صف) حسب تشخيص 66.

-- ============================================================
-- تأكيد — استعلام واحد
--
-- المتوقع: أول أربع صفوف أصفار ✓، والباقي زي ما هو.
-- ============================================================
SELECT البند, العدد::text AS القيمة,
       CASE WHEN متوقع_صفر AND العدد = 0 THEN 'اتنضّف ✓'
            WHEN متوقع_صفر               THEN 'لسه فيه صفوف ✗'
            ELSE 'ما اتلمستش'            END AS الحالة
FROM (
  SELECT 'الحجوزات (course_subscriptions)'::text AS البند,
         (SELECT count(*) FROM public.course_subscriptions) AS العدد,
         true AS متوقع_صفر
  UNION ALL SELECT 'الجلسات',
         (SELECT count(*) FROM public.sessions), true
  UNION ALL SELECT 'تقارير الجلسات',
         (SELECT count(*) FROM public.session_reports), true
  UNION ALL SELECT 'تقييمات مربوطة بحجز',
         (SELECT count(*) FROM public.reviews WHERE booking_id IS NOT NULL), true

  UNION ALL SELECT 'الباقات',
         (SELECT count(*) FROM public.creative_writing_packages), false
  UNION ALL SELECT 'المدربون',
         (SELECT count(*) FROM public.instructors), false
  UNION ALL SELECT 'حسابات المستخدمين',
         (SELECT count(*) FROM public.user_profiles), false
  UNION ALL SELECT 'طلبات الخدمات الإبداعية',
         (SELECT count(*) FROM public.service_orders), false
  UNION ALL SELECT 'عروض مقدّمي الخدمة',
         (SELECT count(*) FROM public.provider_services), false
) t
ORDER BY متوقع_صفر DESC, البند;


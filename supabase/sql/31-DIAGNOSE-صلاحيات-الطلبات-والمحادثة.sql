-- ============================================================
-- 31 — تشخيص: صلاحيات طلبات الخدمات والمحادثة
-- ============================================================
--
-- ملف قراءة فقط. ما بيغيّرش حاجة.
--
-- ليه محتاجه:
--   وأنا ببني لوحة مقدّم الخدمة المستقل لقيت مشكلة في قاعدة البيانات
--   مش في الكود: صلاحية القراءة على جدول الطلبات مكتوبة للمشتري
--   وللمدرب وللإدارة. **مقدّم الخدمة المستقل مش فيهم.**
--
--   يعني حتى لو بنيت له شاشة، قاعدة البيانات هترجّعله صفر طلبات — وده
--   الصح، لأن الصلاحية هي الحارس مش الشاشة. لازم أضيف له صلاحية.
--
--   ونفس السؤال على جدول المحادثة: هل هيقدر يقرا ويكتب رسائل طلبه؟
--
-- القاعدة اللي مشيين عليها: **أي ملف صلاحيات على جدول قايم يبدأ بقراءة
-- الموجود.** الصلاحيات بتتجمع بـOR، فقاعدة زيادة ممكن تفتح باب من غير
-- ما حد ياخد باله. ده حصل قبل كده في المشروع ده.
--
-- شغّل الملف كله وابعتلي الناتج زي ما هو.
-- ============================================================

SELECT
  p.tablename                     AS الجدول,
  p.policyname                    AS القاعدة,
  p.cmd                           AS العملية,
  CASE WHEN p.permissive = 'PERMISSIVE' THEN 'مسموحة (تتجمع بـOR)'
       ELSE 'مقيِّدة' END          AS النوع,
  COALESCE(p.qual, '—')           AS "شرط القراءة/التعديل",
  COALESCE(p.with_check, '—')     AS "شرط الكتابة"
FROM pg_policies p
WHERE p.schemaname = 'public'
  AND p.tablename IN ('service_orders', 'service_order_messages')
ORDER BY p.tablename, p.cmd, p.policyname;


-- ============================================================
-- استعلام تاني: دالة الإشعارات
-- ============================================================
-- المهمة اليومية الجديدة بتشتغل من غير مستخدم مسجّل دخوله (مفيش حد
-- فاتح الموقع الساعة 7 الصبح). محتاج أشوف دالة `notify_user` بتتحقق من
-- إيه — لو بتعتمد على المستخدم الحالي، المهمة مش هتقدر تبعت إشعارات
-- وهتحتاج تعديل.
--
-- شغّله بعد الأول وابعتلي ناتجه كمان.

SELECT
  p.proname                          AS الدالة,
  CASE WHEN p.prosecdef THEN 'SECURITY DEFINER' ELSE 'SECURITY INVOKER' END AS النوع,
  pg_get_functiondef(p.oid)          AS التعريف
FROM pg_proc p
JOIN pg_namespace n ON n.oid = p.pronamespace
WHERE n.nspname = 'public' AND p.proname = 'notify_user';

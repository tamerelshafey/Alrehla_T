-- ============================================================
-- 77 — تنظيف الطلبات التجريبية
-- ============================================================
--
-- ⚠️ **الملف ده بيمسح نهائيًا.** مفيش سلة مهملات في Postgres ومفيش
--    تراجع بعد `COMMIT`. اقرا الأسطر تحت قبل ما تشغّل.
--
-- ── اللي بيتمسح ─────────────────────────────────────────────
--
-- (1) حجز حساب الطفل: `ALR-000013-EZ`
--
--     اتعمل بحساب يوسف (تابع لمحمد حسني) والحارس كان بيفشل مفتوحًا —
--     `getDependentGuardian` كانت بتستعلم `child_profiles` والطفل ممنوع
--     من الجدول، فرجعت `null` والحارس عدّاه. أُصلح في ملف 75.
--
--     ⚠️ ملاحظة على تشخيص ملف 76: دوّرت على الطلب ده في
--     `service_orders` وهو في `course_subscriptions` — «طلب» في كلام
--     تامر كانت تعني حجز باقة. الملف ده بيشيله من الجدول الصح.
--
-- (2) طلبات الخدمات التجريبية الخمسة:
--     ALR-000003-JK (refunded) · ALR-000004-ZS (cancelled) ·
--     ALR-000005-FE · ALR-000006-8Z · ALR-000007-QZ (pending)
--     ومعاها رسائل محادثاتها (3 رسائل).
--
-- ── اللي **مش** بيتمسح ──────────────────────────────────────
--
--     `ALR-000002-KF` — حالته **`paid`** بـ650 ج.م.
--
--     سطره تحت **معلّق عن قصد**. مسح سجل مكتوب عليه «مدفوع» حاجة
--     تتاخد بقرار صريح مش بالجملة، حتى لو البيانات تجريبية. شيل
--     التعليق بنفسك لو متأكد إنه تجريبي.
--
--     وكمان: الحجز `ALR-000012-R3` وجلساته الاثنتي عشرة **ما بتتلمسش**
--     — دي تجربة المسار الشرائي الناجحة، وسجلها مفيد.
--
-- ── الترتيب ─────────────────────────────────────────────────
--
--     الأبناء قبل الآباء عشان المفاتيح الأجنبية. والحذف بالرقم
--     المرجعي مش بالمعرّف الداخلي — أوضح للمراجعة، ولو رقم مش موجود
--     الجملة بتمسح صفر صفوف بلا خطأ.
-- ============================================================

BEGIN;

-- ------------------------------------------------------------
-- 1) رسائل محادثات الطلبات اللي هتتمسح
-- ------------------------------------------------------------
DELETE FROM public.service_order_messages
WHERE order_id IN (
  SELECT id FROM public.service_orders
  WHERE payment_reference IN (
    'ALR-000003-JK',
    'ALR-000004-ZS',
    'ALR-000005-FE',
    'ALR-000006-8Z',
    'ALR-000007-QZ'
    -- ,'ALR-000002-KF'   ← مدفوع. شيل التعليق لو متأكد.
  )
);

-- ------------------------------------------------------------
-- 2) طلبات الخدمات التجريبية
-- ------------------------------------------------------------
DELETE FROM public.service_orders
WHERE payment_reference IN (
  'ALR-000003-JK',
  'ALR-000004-ZS',
  'ALR-000005-FE',
  'ALR-000006-8Z',
  'ALR-000007-QZ'
  -- ,'ALR-000002-KF'   ← مدفوع. شيل التعليق لو متأكد.
);

-- ------------------------------------------------------------
-- 3) حجز حساب الطفل — جلساته الأول لو اتولّدت
--
--    الحجز ده ما اتأكّدش دفعه، فالمفروض مالوش جلسات. الجملة دي
--    احتياط: لو اتولّدت بأي طريقة، مسح الحجز وحده كان هيسيبها يتيمة.
-- ------------------------------------------------------------
DELETE FROM public.sessions
WHERE course_subscription_id IN (
  SELECT id FROM public.course_subscriptions
  WHERE payment_reference = 'ALR-000013-EZ'
);

DELETE FROM public.course_subscriptions
WHERE payment_reference = 'ALR-000013-EZ';

COMMIT;

-- ============================================================
-- تأكيد — استعلام واحد
--
-- المتوقع: الطلبات التجريبية اختفت، و`ALR-000012-R3` وجلساته
-- الاثنتي عشرة زي ما هي.
-- ============================================================
SELECT القسم, البند, التفاصيل, الحالة FROM (

  SELECT '1. طلبات الخدمات'::text AS القسم,
         COALESCE(so.payment_reference, left(so.id, 8)) AS البند,
         COALESCE(ss.name, 'خدمة محذوفة') || ' · ' || so.status AS التفاصيل,
         CASE WHEN so.status = 'paid' THEN '⚠️ مدفوع — اتساب'
              ELSE 'لسه موجود' END AS الحالة
  FROM public.service_orders so
  LEFT JOIN public.standalone_services ss ON ss.id = so.standalone_service_id

  UNION ALL

  SELECT '2. الحجوزات',
         COALESCE(cs.payment_reference, left(cs.id, 8)),
         COALESCE(p.name, 'باقة محذوفة') || ' · ' || cs.status,
         (SELECT count(*)::text FROM public.sessions s
          WHERE s.course_subscription_id = cs.id) || ' جلسة'
  FROM public.course_subscriptions cs
  LEFT JOIN public.creative_writing_packages p ON p.id = cs.package_id

  UNION ALL

  SELECT '3. الخلاصة', البند, العدد::text,
         CASE WHEN متوقع_صفر AND العدد = 0 THEN 'اتنضّف ✓'
              WHEN متوقع_صفر               THEN 'لسه فيه صفوف ✗'
              ELSE 'ما اتلمسش' END
  FROM (
    SELECT 'حجز ALR-000013-EZ'::text AS البند,
           (SELECT count(*) FROM public.course_subscriptions
            WHERE payment_reference = 'ALR-000013-EZ') AS العدد,
           true AS متوقع_صفر
    UNION ALL
    SELECT 'رسائل المحادثة',
           (SELECT count(*) FROM public.service_order_messages), true
    UNION ALL
    SELECT 'الجلسات',
           (SELECT count(*) FROM public.sessions), false
    UNION ALL
    SELECT 'حسابات المستخدمين',
           (SELECT count(*) FROM public.user_profiles), false
  ) x

) t ORDER BY القسم, البند;


-- ============================================================
-- 56 — إزالة القراءة العامة لجدول المستخدمين (المرحلة التانية)
-- ============================================================
--
-- ⛔ ما تشغّلش الملف ده غير بعد ما تجرّب الحاجات دي وتتأكد إنها شغّالة،
--    لأن السياسة الجديدة (ملف 54) هي اللي هتحكم لوحدها بعده:
--
--      1. شاشة المستخدمين في لوحة الإدارة — الأسماء ظاهرة؟
--      2. صفحة مدرب فيها مراجعات — اسم كاتب المراجعة ظاهر **وإنت خارج
--         من حسابك**؟
--      3. محادثة طلب خدمة — كل طرف شايف اسم التاني؟
--      4. شاشة طلاب المدرب — الأسماء ظاهرة؟
--      5. شاشة طلبات حذف الحسابات — الأسماء ظاهرة؟
--
--    لو أي واحدة فيهم عرضت «مستخدم» أو فضيت، **بلّغني قبل ما تشغّل ده**.
--
-- اللي بيتشال:
--      "Profiles are viewable by everyone"  USING (true)
--
--   دي اللي بتخلي أي زائر — من غير تسجيل دخول — يسحب قايمة بكل
--   مستخدمين المنصة بأسمائهم وأدوارهم، ويعرف مين الإداريين.
--
-- بعد الإزالة بيفضل شغّال:
--      "Users can view their own profile"        (صاحب الحساب)
--      "Profiles visible to those who need them" (الدالة بتاعت ملف 54)
--
-- التراجع في آخر الملف — سطر واحد يرجّع الوضع القديم فورًا.
-- ============================================================

BEGIN;

DROP POLICY IF EXISTS "Profiles are viewable by everyone" ON public.user_profiles;

COMMIT;

-- ============================================================
-- تأكيد — استعلام واحد
-- ============================================================
SELECT
  p.polname AS السياسة,
  coalesce(pg_get_expr(p.polqual, p.polrelid), '—') AS الشرط
FROM pg_policy p
JOIN pg_class c ON c.oid = p.polrelid
WHERE c.relname = 'user_profiles' AND p.polcmd = 'r'
ORDER BY p.polname;


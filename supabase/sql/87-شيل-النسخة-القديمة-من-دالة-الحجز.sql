-- ============================================================
-- 87 — شيل النسخة القديمة من دالة الحجز (عاجل)
-- ============================================================
--
-- 🔴 **شغّله دلوقتي.** حجز الباقات واقع على الإنتاج لحد ما يتشغّل.
--
-- ── إيه اللي حصل ────────────────────────────────────────────
--
-- ملف 86 عمل `CREATE OR REPLACE` لدالة بخمس باراميترات. ورأس الملف
-- كان بيقول إن ده **بيستبدل** نسخة الأربع باراميترات. **وده غلط.**
--
-- `CREATE OR REPLACE FUNCTION` بتستبدل الدالة اللي **بنفس التوقيع**
-- بالظبط. وتغيير عدد الباراميترات بيعمل **تحميلًا زائدًا (overload)
-- جديدًا** — فبقى عندنا دالتين بنفس الاسم:
--
--     create_course_booking(text, text, text, text)        ← القديمة
--     create_course_booking(text, text, text, text, text)  ← ملف 86
--
-- ── وليه ده كسر الموقع ──────────────────────────────────────
--
-- الكود المنشور حاليًا بينادي الدالة بـ**أربع** باراميترات بأسمائها.
-- والنداء ده بيطابق **الاتنين**: القديمة بالظبط، والجديدة كمان لأن
-- الباراميتر الخامس عنده `DEFAULT NULL`.
--
-- فـPostgres مبيقدرش يختار، وبيرجّع:
--
--     function public.create_course_booking(...) is not unique
--
-- يعني **كل حجز جديد بيقع** — سواء بالكود القديم أو الجديد.
--
-- ── الحل ────────────────────────────────────────────────────
--
-- تشيل القديمة. ساعتها النداء بأربع باراميترات (الكود المنشور
-- دلوقتي) هيطابق الجديدة وحدها والإهداء هيتكتب NULL — يعني
-- **الموقع بيرجع يشتغل فورًا قبل ما تدفع الكود الجديد**، والإهداء
-- بيشتغل لما تدفعه.
--
-- ⚠️ `DROP` من غير `CASCADE` عن قصد (قاعدة §3). لو رجّع خطأ إن في
--    حاجة معتمدة عليها، **متضفش CASCADE** — ابعتلي نص الخطأ.
-- ============================================================

BEGIN;

DROP FUNCTION IF EXISTS
  public.create_course_booking(text, text, text, text);

COMMIT;

-- ============================================================
-- استعلام التأكيد — واحد
-- ============================================================

SELECT القسم, البند, التفاصيل, الحالة FROM (

  -- ١) نسخة واحدة بس فاضلة
  SELECT
    '1. عدد النسخ'::text AS القسم,
    'create_course_booking'::text AS البند,
    ('نسخ موجودة: ' || count(*)::text
      || '  ·  التواقيع: '
      || COALESCE(string_agg(p.pronargs::text, ' / ' ORDER BY p.pronargs), '—'))::text
      AS التفاصيل,
    CASE
      WHEN count(*) = 1 AND max(p.pronargs) = 5 THEN '✓ نسخة واحدة بخمسة'
      WHEN count(*) > 1 THEN '✗ لسه فيه تحميل زائد — الحجز هيفضل واقع'
      ELSE '✗ الدالة مش موجودة'
    END AS الحالة
  FROM pg_proc p
  JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public' AND p.proname = 'create_course_booking'

  UNION ALL

  -- ٢) الصلاحيات على النسخة الفاضلة
  SELECT
    '2. الصلاحيات',
    'create_course_booking',
    'anon: ' || CASE WHEN has_function_privilege('anon', p.oid, 'EXECUTE')
                     THEN 'نعم' ELSE 'لأ' END
    || '  ·  authenticated: ' || CASE WHEN has_function_privilege('authenticated', p.oid, 'EXECUTE')
                     THEN 'نعم' ELSE 'لأ' END,
    CASE
      WHEN NOT has_function_privilege('anon', p.oid, 'EXECUTE')
       AND has_function_privilege('authenticated', p.oid, 'EXECUTE')
        THEN '✓ الزائر ممنوع'
      ELSE '✗ راجع'
    END
  FROM pg_proc p
  JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public' AND p.proname = 'create_course_booking'

) t ORDER BY القسم, البند;


-- ============================================================
-- 37 — إضافة دور «مقدّم خدمة» لأدوار المستخدمين
-- ============================================================
--
-- المشكلة:
--   بقى عندنا مقدّمو خدمة مستقلين (مش مدربين)، وليهم لوحة تحكم خاصة
--   بيهم. لكن عمود الدور في `user_profiles` نوعه `user_role_enum`،
--   والقيم المسموح بيها فيه هي:
--       visitor, customer, student, instructor, publisher,
--       general_supervisor, super_admin
--   مفيش فيها «مقدّم خدمة». يعني الحساب بيفضل «student» وبيتوجّه للوحة
--   المتدرب بدل لوحة مقدّم الخدمة.
--
-- الحل:
--   إضافة قيمة واحدة جديدة للنوع: service_provider.
--
-- إيه اللي بيتغيّر فعليًا:
--   القيم المسموح بيها في النوع بس. مفيش جدول اتعمل، مفيش عمود اتغيّر،
--   ومفيش صف واحد اتمس. كل الحسابات القايمة بتفضل بأدوارها زي ما هي.
--   الإضافة دي ما ينفعش تترجع بسهولة في Postgres (حذف قيمة من enum
--   مش مدعوم) — بس مفيش ضرر في وجودها حتى لو ما اتستخدمتش.
--
-- ⚠️ مفيش BEGIN/COMMIT هنا عن قصد:
--   Postgres ما بيسمحش باستخدام قيمة enum جديدة في نفس المعاملة اللي
--   أضافتها. فبنضيفها لوحدها، والتأكيد بيتعمل بعدها في استعلام منفصل.
--
-- شغّل السطر ده لوحده، وبعدين استعلام التأكيد تحته.
-- ============================================================

ALTER TYPE public.user_role_enum ADD VALUE IF NOT EXISTS 'service_provider';

-- ============================================================
-- تأكيد — استعلام واحد (شغّله بعد اللي فوق)
-- ============================================================
SELECT
  string_agg(e.enumlabel, ' | ' ORDER BY e.enumsortorder) AS الأدوار_المتاحة,
  CASE WHEN bool_or(e.enumlabel = 'service_provider')
       THEN 'دور مقدّم الخدمة موجود ✓'
       ELSE 'لسه مش موجود ✗' END AS النتيجة
FROM pg_enum e
JOIN pg_type t ON t.oid = e.enumtypid
JOIN pg_namespace n ON n.oid = t.typnamespace
WHERE n.nspname = 'public' AND t.typname = 'user_role_enum';

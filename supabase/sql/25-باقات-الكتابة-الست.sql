-- ── ربط الاشتراط: «صانع الحكاية» بعد «صياغة الأثر» ──────────
-- الجدول فيه عمود prerequisite_package_id بيربط الرحلة بالرحلة
-- المطلوبة قبلها. بنملاه بعد الإدخال لأن الرحلتين لازم يكونا موجودين.

UPDATE creative_writing_packages
SET prerequisite_package_id = (
      SELECT id FROM creative_writing_packages WHERE slug = 'crafting-impact'
    )
WHERE slug = 'story-maker'
  AND prerequisite_package_id IS NULL;

COMMIT;

-- ============================================================
-- تأكيد — استعلام واحد
-- ============================================================
SELECT
  p.name                               AS الرحلة,
  p.age_group::text                    AS الفئة,
  p.duration_text                      AS المدة,
  p.sessions_count                     AS الجلسات,
  p.price                              AS السعر,
  CASE WHEN p.is_active THEN 'منشورة' ELSE 'مخفية — محتاجة سعر' END AS الحالة,
  COALESCE(pre.name, '—')              AS "تشترط إتمام"
FROM creative_writing_packages p
LEFT JOIN creative_writing_packages pre ON pre.id = p.prerequisite_package_id
ORDER BY p.age_group, p.sessions_count;

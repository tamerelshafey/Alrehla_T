  COALESCE(pre.name, '—')                  AS "تشترط إتمام",
  CASE WHEN COALESCE(btrim(p.target_audience), '') = '' THEN '✗' ELSE '✓' END AS "لمن تناسب",
  CASE WHEN COALESCE(btrim(p.short_description), '') = '' THEN '✗' ELSE '✓' END AS "وصف مختصر",
  CASE WHEN COALESCE(btrim(p.full_description), '') = '' THEN '✗' ELSE '✓' END AS "وصف كامل"
FROM creative_writing_packages p
LEFT JOIN creative_writing_packages pre ON pre.id = p.prerequisite_package_id
ORDER BY p.age_group, p.sessions_count;

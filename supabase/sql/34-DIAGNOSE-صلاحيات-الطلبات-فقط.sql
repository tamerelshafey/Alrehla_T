-- ============================================================
-- 34 — تشخيص: صلاحيات الطلبات والمحادثة (استعلام واحد)
-- ============================================================
--
-- ملف قراءة فقط. ما بيغيّرش حاجة.
--
-- ده نفس الاستعلام الأول اللي كان في ملف 31، بس لوحده في ملف منفصل —
-- لأن محرّر Supabase بيعرض آخر نتيجة بس، وملف 31 كان فيه استعلامين.
--
-- ليه محتاجه:
--   مقدّم الخدمة المستقل لسه **مش هيشوف طلباته**. صلاحية القراءة على
--   جدول الطلبات مكتوبة للمشتري وللمدرب وللإدارة — هو مش فيهم. الشاشة
--   اللي اتبنت له هترجّع صفر، وده الصح: الصلاحية هي الحارس مش الشاشة.
--
--   وما هكتبش صلاحيات من غير ما أشوف الموجود. الصلاحيات بتتجمع بـOR،
--   فقاعدة زيادة ممكن تفتح باب من غير ما حد ياخد باله — وده حصل في
--   المشروع ده تلات مرات قبل كده.
--
-- شغّل الملف كله وابعتلي الناتج زي ما هو.
-- ============================================================

SELECT
  p.tablename                     AS الجدول,
  p.cmd                           AS العملية,
  p.policyname                    AS القاعدة,
  CASE WHEN p.permissive = 'PERMISSIVE' THEN 'مسموحة' ELSE 'مقيِّدة' END AS النوع,
  COALESCE(p.qual, '—')           AS "شرط القراءة/التعديل",
  COALESCE(p.with_check, '—')     AS "شرط الكتابة"
FROM pg_policies p
WHERE p.schemaname = 'public'
  AND p.tablename IN ('service_orders', 'service_order_messages')
ORDER BY p.tablename, p.cmd, p.policyname;

--
-- ============================================================
-- 53 — تشخيص: ليه الباقات مختلفة بين الشاشتين؟
-- ============================================================
-- ملاحظتك:
--   • الباقات في قايمة الاختيار (معالج الحجز) مختلفة عن الباقات في
--     صفحة الباقات.
--   • بيانات المدة مش ظاهرة في كل الباقات.
--
-- الفرق بين الشاشتين في الكود:
--   معالج الحجز بيعرض **كل** باقة مفعّلة.
--   صفحة الباقات بتقسّمهم لمجموعتين: «دون 12» و«12 فأكثر» — فأي باقة
--   فئتها العمرية مش واحدة من الاتنين دول **بتختفي من الصفحة** وتفضل
--   ظاهرة في المعالج.
--
-- والمدة: عمود `duration_text` بيتساب فاضي في الباقات اللي اتضافت
-- يدويًا، فبيختفي السطر بتاعه من الكارت.
--
-- الاستعلام ده بيطلّع الحقيقة: كل باقة وحالتها وفئتها وبياناتها.
-- ============================================================

SELECT
  name                                   AS الباقة,
  CASE WHEN is_active THEN 'مفعّلة' ELSE 'موقوفة' END AS الحالة,
  age_group                              AS الفئة_العمرية,
  CASE
    WHEN age_group IN ('under_12', '12_plus') THEN 'بتظهر في الصفحة ✓'
    ELSE 'مختفية من صفحة الباقات ✗'
  END                                    AS ظهورها,
  price                                  AS السعر,
  coalesce(duration_text, '— فاضي ✗')     AS المدة,
  coalesce(sessions_count::text, '— فاضي ✗') AS عدد_الجلسات,
  coalesce(session_duration, '— فاضي ✗')  AS مدة_الجلسة
FROM creative_writing_packages
ORDER BY is_active DESC, age_group, name;
